def main():
    with open(PATH, encoding='utf-8') as f:
        data = json.load(f)
    existing_units = {u['id'] for u in data['units']}
    existing_ids = {
        item['id']
        for u in data['units']
        for l in u.get('lessons', [])
        for item in l.get('vocab', [])
    }
    collisions = [
        item['id']
        for unit in (U24, U25)
        for l in unit['lessons']
        for item in l['vocab']
        if item['id'] in existing_ids
    ]
    if collisions:
        print('FATAL: vocab id collisions:', sorted(set(collisions)))
        sys.exit(1)
    added = 0
    for unit in (U24, U25):
        if unit['id'] not in existing_units:
            data['units'].append(unit)
            added += 1
    with open(PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write('\n')
    words = sum(
        len(l['vocab']) for unit in (U24, U25) for l in unit['lessons'])
    print(f'ur: appended {added} units, {words} words '
          f'(total units now {len(data["units"])})')


if __name__ == '__main__':
    main()
