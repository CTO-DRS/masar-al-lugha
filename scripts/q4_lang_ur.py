def frames_for(cls, word, course):
    if cls == "verb":
        return VERB
    if cls == "num":
        return NUM
    if cls == "noun":
        t = (word.get("translationAr") or "").strip()
        return NOUN_FRAMES.get(noun_subtype(t), NOUN_FRAMES[None])
    if cls == "phrase_q":
        return SENTENCE_Q
    if cls == "phrase_i":
        return PHRASE_I
    if cls == "imperative":
        return IMPERATIVE
    if cls == "sentence":
        return DIRECT
    return []  # adj/adv/interject are hand-authored in the bank


